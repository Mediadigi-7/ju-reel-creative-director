import assert from 'node:assert/strict';
import { generateOfflineStoryboard } from '../shared/offline/index.js';
import { SIX_STAGE_CONTRACT, sixStageIssues } from '../shared/narrativeStages.js';
import { informationIntegrityIssues } from './informationIntegrity.js';
import { encodeStoryboardForUrl, decodeStoryboardFromUrl } from '../src/services/shareUtils.js';
import { validateAndRepairStoryboard } from '../shared/schema.js';
const base={...generateOfflineStoryboard('AI will change these careers'),narrativeContract:SIX_STAGE_CONTRACT};
assert.deepEqual(sixStageIssues(base),[]);
const eight=structuredClone(base);eight.shots.splice(4,0,structuredClone(base.shots[3]),structuredClone(base.shots[3]));
assert.deepEqual(sixStageIssues(eight),[],'Additional shots can extend a stage without imposing six shots exactly');
const three=structuredClone(base);three.shots=three.shots.slice(0,3);
three.shots.forEach(s=>{s.functions=['HOOK','PROBLEM','PATTERN_INTERRUPT','VALUE','PAYOFF','CTA'];});
assert.ok(sixStageIssues(three).some(i=>i.includes('Missing required stage')),'Combined labels cannot disguise missing primary stages');
const reversed=structuredClone(base);[reversed.shots[0],reversed.shots[1]]=[reversed.shots[1],reversed.shots[0]];
assert.ok(sixStageIssues(reversed).some(i=>i.includes('in order')));
const emptyCta=structuredClone(base);emptyCta.shots.at(-1)!.dialogue='';emptyCta.shots.at(-1)!.onscreenText='';
assert.ok(sixStageIssues(emptyCta).some(i=>i.includes('actual spoken or visible')));
const duplicate=structuredClone(base);duplicate.shots.push(structuredClone(base.shots.at(-1)!));
assert.ok(sixStageIssues(duplicate).some(i=>i.includes('exactly one')));
const shared=decodeStoryboardFromUrl(encodeStoryboardForUrl(base));
assert.equal(shared?.narrativeContract,SIX_STAGE_CONTRACT);
assert.equal(validateAndRepairStoryboard(base,base.reelTitle).data.narrativeContract,SIX_STAGE_CONTRACT);
const bad=structuredClone(base);bad.shots[0].dialogue='If you enjoy the logic over the business context, you might lean towards BBA.';
assert.equal(informationIntegrityIssues(bad).length,1,'Reject the observed degree-fit failure');
bad.shots[0].dialogue='This does not mean you should lean towards BBA. Compare the actual assignments first.';
assert.deepEqual(informationIntegrityIssues(bad),[],'A qualified caution is not a recommendation');
console.log('PASS: ordered six stages, additional shots, no tag-only coverage, meaningful final CTA, metadata sharing, and degree-fit regression guard');
