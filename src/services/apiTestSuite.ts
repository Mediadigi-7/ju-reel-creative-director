import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { CompactTopBar } from '../components/CompactTopBar.js';
import { validateAndRepairStoryboard } from '../../shared/schema.js';
import { apiGenerateReel, apiRegenerateShot } from './api.js';
import { generateKnowledgeEngineStoryboard } from '../../server/knowledgeEngine.js';
const original = globalThis.fetch;
const request = { reelTitle: 'B.Com vs BBA', apiKey: 'test-only-key', apiProvider: 'openai' as const };
try {
  const offline = generateKnowledgeEngineStoryboard('What should I study after Commerce?');
  assert.equal(offline.generation?.source, 'offline');
  globalThis.fetch = async () => { throw new Error('network unavailable'); };
  await assert.rejects(apiGenerateReel(request), /Cannot reach/);
  await assert.rejects(apiRegenerateShot({ ...request, creativeAngle: offline.creativeAngle, targetAudience: offline.targetAudience, shotNumber: 1, shotType: 'HOOK', currentStoryboard: offline }), /Cannot reach/);
  globalThis.fetch = async () => new Response(JSON.stringify({ success: true, data: offline }));
  await assert.rejects(apiGenerateReel(request), /did not confirm an AI source/);
  globalThis.fetch = async () => new Response(JSON.stringify({ error: 'failed' }), { status: 500 });
  await assert.rejects(apiGenerateReel(request), /Generation failed/);
  globalThis.fetch = async () => new Response('<html>no API</html>');
  await assert.rejects(apiGenerateReel(request), /invalid response/);
  globalThis.fetch = async () => { throw new Error('network unavailable'); };
  await assert.rejects(apiGenerateReel({ reelTitle: 'AI will change these careers' }),/Cannot reach/); // A server-side provider key may exist; no silent offline substitution.
  const live = { ...offline, generation: { source: 'openai' as const, model: 'gpt-4o-mini', generatedAt: new Date().toISOString() } };
  globalThis.fetch = async () => new Response(JSON.stringify({ success: true, data: live }));
  assert.equal((await apiGenerateReel(request)).generation?.source, 'openai');
  assert.equal(validateAndRepairStoryboard(live, live.reelTitle).data.generation.source, 'openai');
  const props = { reel: live, openedFrom: 'library' as const, onBack() {}, onRegenerateAll() {}, onExportPdf() {}, onShareLink() {}, onCopyWhatsApp() {}, onCopyBrief() {}, onSave() {}, isRegenerating: false, isSaved: true };
  const html = renderToStaticMarkup(React.createElement(CompactTopBar, props));
  assert.match(html, /Opened from library/);
  assert.match(html, /Generated by OpenAI/);
  assert.match(html, /gpt-4o-mini/);
  const legacy = { ...offline }; delete legacy.generation;
  assert.match(renderToStaticMarkup(React.createElement(CompactTopBar, { ...props, reel: legacy })), /Source unknown/);
  console.log('PASS: source survives validation; library, model, and legacy labels render');
  console.log('PASS: live network, HTTP, invalid JSON, and fallback responses rejected; no-key offline labelled; confirmed live source preserved');
} finally { globalThis.fetch = original; }
